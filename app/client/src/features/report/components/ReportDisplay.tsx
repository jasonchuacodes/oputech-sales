import { ContentSection } from '../../../components'
import { DataTable, DataTableColumn } from '../../../components/ui/data-table'
import { cn } from '../../../utils/cn'
import { formatCurrency } from '../../../utils/number'
import { dayjsLocal, formatDate, formatTime } from '../../../utils/date'
import {
  ProductSale,
  Report,
  ReportExpense,
} from '../../../services/report/report.types'
import { PaymentType } from '../../../services/transaction/transaction.types'
import { UserRole } from '../../../types'
import { useAuthContext } from '../../../context/auth/useAuthContext'
import { ReportDetailActions } from './ReportDetailActions'

interface Props {
  report: Report
  onDelete?: (id: string) => void
}

const productColumns: DataTableColumn<ProductSale>[] = [
  {
    id: 'name',
    heading: 'Product',
    orderable: true,
    cell: (p) => p.name,
  },
  {
    id: 'quantitySold',
    heading: 'Qty Sold',
    cell: (p) => p.quantitySold,
  },
  {
    id: 'pricePerUnit',
    heading: 'Price / Unit',
    cell: (p) => formatCurrency(p.pricePerUnit),
  },
  {
    id: 'total',
    heading: 'Total',
    cell: (p) => <span className="font-medium">{formatCurrency(p.total)}</span>,
  },
]

const expenseColumns: DataTableColumn<ReportExpense>[] = [
  {
    id: 'label',
    heading: 'Label',
    cell: (e) => e.label,
  },
  {
    id: 'paymentType',
    heading: 'Payment',
    cell: (e) => (e.paymentType === PaymentType.Cash ? 'Cash' : 'Online'),
  },
  {
    id: 'total',
    heading: 'Amount',
    cell: (e) => <span className="font-medium">{formatCurrency(e.total)}</span>,
  },
]

export const ReportDisplay = ({ report, onDelete }: Props) => {
  const { auth } = useAuthContext()
  const isAdmin = auth?.role !== UserRole.STAFF

  return (
    <div className="flex flex-col gap-4">
      <div className="rounded-card bg-card shadow-card flex flex-col gap-5 p-4 md:p-5">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
          <div className="flex flex-col gap-1">
            <p className="text-sm text-slate-500">
              Generated by{' '}
              <span className="text-text-heading font-medium">
                {report.createdBy.username}
              </span>{' '}
              · {formatDate(report.createdAt)} at {formatTime(report.createdAt)}
            </p>
            {!dayjsLocal(report.fromDate).isSame(
              dayjsLocal(report.toDate),
              'day'
            ) && (
              <p className="text-sm text-slate-500">
                Period: {formatDate(report.fromDate)} —{' '}
                {formatDate(report.toDate)}
              </p>
            )}
          </div>
          <div className="flex items-center justify-between gap-2 sm:justify-end">
            <span className="flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-xs font-medium">
              <span
                className={cn(
                  'h-2 w-2 shrink-0 rounded-full',
                  report.isRemitted ? 'bg-green-500' : 'bg-gray-400'
                )}
              />
              {report.isRemitted ? 'Remitted' : 'Not remitted'}
            </span>
            {(isAdmin || onDelete) && (
              <ReportDetailActions
                reportId={report.id}
                isRemitted={report.isRemitted}
                canRemit={isAdmin}
                onDelete={onDelete ? () => onDelete(report.id) : undefined}
              />
            )}
          </div>
        </div>

        <div className="grid grid-cols-2 gap-2 sm:grid-cols-3 sm:gap-3 lg:grid-cols-5">
          <div className="bg-background flex flex-col gap-1 rounded-md p-3 sm:p-4">
            <span className="text-xs font-medium text-slate-500">Cash</span>
            <span className="text-foreground text-metric-md font-semibold">
              {formatCurrency(report.totalCash)}
            </span>
          </div>
          <div className="bg-background flex flex-col gap-1 rounded-md p-3 sm:p-4">
            <span className="text-xs font-medium text-slate-500">Online</span>
            <span className="text-foreground text-metric-md font-semibold">
              {formatCurrency(report.totalOnline)}
            </span>
          </div>
          <div className="bg-background flex flex-col gap-1 rounded-md p-3 sm:p-4">
            <span className="text-xs font-medium text-slate-500">Expenses</span>
            <span className="text-foreground text-metric-md font-semibold">
              {formatCurrency(report.totalExpenses)}
            </span>
          </div>
          <div className="bg-primary text-primary-foreground order-first col-span-2 flex flex-col gap-1 rounded-md p-4 sm:order-none sm:col-span-1">
            <span className="text-primary-foreground/70 text-xs font-medium">
              Total Income
            </span>
            <span className="text-metric-md font-semibold">
              {formatCurrency(report.totalIncome)}
            </span>
          </div>
          <div className="bg-background flex flex-col gap-1 rounded-md p-3 sm:p-4">
            <span className="text-xs font-medium text-slate-500">
              Total Prints
            </span>
            <span className="text-foreground text-metric-md font-semibold">
              {report.totalPrintCount.toLocaleString()}
            </span>
          </div>
        </div>

        <ContentSection label="Products sold">
          <div className="md:hidden">
            <MobileProductSales items={report.products} />
          </div>
          <div className="hidden md:block">
            <DataTable
              collection={DataTable.collection({
                items: report.products,
                itemToValue: (p) => p.productId,
                itemToString: (p) => p.name,
              })}
              columns={productColumns}
              emptyMessage="No transactions found in this date range."
            />
          </div>
        </ContentSection>

        <ContentSection label="Expenses">
          <DataTable
            collection={DataTable.collection({
              items: report.expenses,
              itemToValue: (e) => e.id,
              itemToString: (e) => e.label ?? e.id,
            })}
            columns={expenseColumns}
            emptyMessage="No expenses logged in this date range."
          />
        </ContentSection>
      </div>
    </div>
  )
}

const MobileProductSales = ({ items }: { items: ProductSale[] }) => {
  if (items.length === 0) {
    return (
      <div className="rounded-card bg-card p-4 text-center text-sm text-text-secondary shadow-card">
        No transactions found in this date range.
      </div>
    )
  }

  return (
    <ul className="rounded-card bg-card overflow-hidden shadow-card">
      {items.map((product) => (
        <li
          key={product.productId}
          className="border-border/60 flex min-h-20 items-center gap-3 border-b p-3 last:border-b-0"
        >
          <span className="flex min-w-0 flex-1 flex-col gap-1">
            <span className="text-text-heading truncate font-medium">
              {product.name}
            </span>
            <span className="text-text-tertiary text-sm">
              {product.quantitySold.toLocaleString()} sold ·{' '}
              {formatCurrency(product.pricePerUnit)} each
            </span>
          </span>
          <span className="flex shrink-0 items-center gap-1">
            <span className="flex flex-col items-end gap-1">
              <span className="font-semibold whitespace-nowrap">
                {formatCurrency(product.total)}
              </span>
            </span>
          </span>
        </li>
      ))}
    </ul>
  )
}
